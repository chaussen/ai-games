// Packs content/*.json into content.js, the one file the server and the browser both load.
// content.js is GENERATED: edit the JSON, then run `node tools/pack.mjs`.
// `node tools/pack.mjs --check` exits 1 if content.js is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = f => JSON.parse(fs.readFileSync(path.join(root, 'content', f), 'utf8'));

export function build() {
  const g = read('glyphs.json');
  const order = read('order.json');
  const stages = order.map(id => {
    const L = read('stages/' + id + '.json');
    if (L.id !== id) throw new Error('content/stages/' + id + '.json has id "' + L.id + '"; file name and id must match');
    return L;
  });
  const data = { glyphs: g.glyphs, recipes: g.recipes, stages };
  return '// GENERATED by tools/pack.mjs from content/*.json. Do not edit by hand.\n' +
    '(function (root) {\n  const data = ' + JSON.stringify(data) + ';\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n  else root.WContent = data;\n" +
    "})(typeof window !== 'undefined' ? window : globalThis);\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(root, 'content.js');
  const text = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (cur !== text) { console.error('content.js is out of date: run `node tools/pack.mjs`'); process.exit(1); }
    console.log('content.js is up to date');
  } else {
    fs.writeFileSync(out, text);
    console.log('wrote content.js');
  }
}

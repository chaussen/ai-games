// tools/pack.mjs: pack cards.json into content.js for browser and server (docs/GLYPH-CARDS.md: cards live in
// cards.json, generated into content.js as forge-2d does). Run after every cards.json change:
//   node tools/pack.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const src = JSON.parse(fs.readFileSync(path.join(root, 'cards.json'), 'utf8'));
const cards = src.cards.filter(c => c && c.ch);
const dup = cards.filter((c, i) => cards.findIndex(o => o.ch === c.ch) !== i);
if (dup.length) { console.error('duplicate characters in cards.json: ' + dup.map(c => c.ch).join(' ')); process.exit(1); }
const out = `(// GENERATED by tools/pack.mjs from cards.json. Do not edit by hand; edit cards.json and re-run.
function (root) {
  const data = {"cards":${JSON.stringify(cards)}};
  if (typeof module !== 'undefined' && module.exports) module.exports = data;
  else root.WContent = data;
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(root, 'content.js'), out);
console.log(`content.js: ${cards.length} cards, ${(fs.statSync(path.join(root, 'content.js')).size / 1024).toFixed(1)} KB`);

import { spawn } from 'node:child_process';
const PORT = 3419;
const proc = spawn(process.execPath, ['server.js'], { cwd: process.cwd(), env: { ...process.env, PORT: String(PORT) }, stdio: ['ignore','pipe','pipe'] });
proc.stderr.on('data', () => {});
await new Promise(r => setTimeout(r, 500));
const ws = new WebSocket('ws://127.0.0.1:' + PORT + '/ws');
let last = null;
ws.onopen = () => ws.send(JSON.stringify({type:'join', name:'TV', board:true}));
ws.onmessage = ev => { const m = JSON.parse(ev.data); if (m.type==='state') last=m; };
await new Promise(r => setTimeout(r, 300));
for (let i=0;i<4;i++) ws.send(JSON.stringify({type:'addBot'}));
ws.send(JSON.stringify({type:'start'}));
await new Promise(r => setTimeout(r, 13000));
const s = last;
console.log('CORE:', JSON.stringify(s.bodies.find(b=>b.kind==='core')));
console.log('NEARBY BODIES (x 1050..1450):');
console.log(JSON.stringify(s.bodies.filter(b => b.x > 1050 && b.x < 1450 && b.kind !== 'rope'), null, 1));
console.log('ALL NON-STATIC:', JSON.stringify(s.bodies.filter(b => ['crate','plank','barrel'].includes(b.kind)), null, 1));
proc.kill();
